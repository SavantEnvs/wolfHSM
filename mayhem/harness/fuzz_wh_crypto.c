#ifdef HAVE_HKDF
static int fuzz_CryptoHkdf(whClientContext* ctx, int devId, char* data, size_t size)
{
#define WH_TEST_HKDF_IKM_SIZE 22
#define WH_TEST_HKDF_SALT_SIZE 13
#define WH_TEST_HKDF_INFO_SIZE 10
#define WH_TEST_HKDF_OKM_SIZE 42

    /* Test vectors from RFC 5869 Test Case 1 */
    uint8_t ikm[WH_TEST_HKDF_IKM_SIZE] = {0};
    uint8_t salt[WH_TEST_HKDF_SALT_SIZE] = {0};
    uint8_t info[WH_TEST_HKDF_INFO_SIZE] = {0};

    uint8_t okm[WH_TEST_HKDF_OKM_SIZE];
    whKeyId key_id  = WH_KEYID_ERASED;
    uint8_t label[] = "HKDF Test Label";

    size_t cur = 0;
    size_t ikm_len = 0, salt_len = 0, info_len = 0, okm_len = 0;

    /* Split input buffer */
    ikm_len = (size - cur) ? (size - cur) : 0;
    if (ikm_len > WH_TEST_HKDF_IKM_SIZE) ikm_len = WH_TEST_HKDF_IKM_SIZE;
    if (ikm_len > 0) {
        memcpy(ikm, data + cur, ikm_len);
        cur += ikm_len;
    }

    salt_len = (size - cur) ? (size - cur) : 0;
    if (salt_len > WH_TEST_HKDF_SALT_SIZE) salt_len = WH_TEST_HKDF_SALT_SIZE;
    if (salt_len > 0) {
        memcpy(salt, data + cur, salt_len);
        cur += salt_len;
    }

    info_len = (size - cur) ? (size - cur) : 0;
    if (info_len > WH_TEST_HKDF_INFO_SIZE) info_len = WH_TEST_HKDF_INFO_SIZE;
    if (info_len > 0) {
        memcpy(info, data + cur, info_len);
        cur += info_len;
    }

    /* Decide OKM length from remaining bytes (or default to 16) */
    okm_len = (size - cur) ? (size - cur) % (WH_TEST_HKDF_OKM_SIZE + 1) : 16;
    if (okm_len == 0) okm_len = 16;
    if (okm_len > WH_TEST_HKDF_OKM_SIZE) okm_len = WH_TEST_HKDF_OKM_SIZE;

    /* Zero any unused bytes to keep comparisons clean */
    if (ikm_len < sizeof(ikm)) memset(ikm + ikm_len, 0, sizeof(ikm) - ikm_len);
    if (salt_len < sizeof(salt)) memset(salt + salt_len, 0, sizeof(salt) - salt_len);
    if (info_len < sizeof(info)) memset(info + info_len, 0, sizeof(info) - info_len);

    /* Test 1: Direct wc_HKDF call (uses crypto callback) */
    memset(okm, 0, sizeof(okm));
    wc_HKDF_ex(WC_SHA256, ikm, WH_TEST_HKDF_IKM_SIZE, salt, WH_TEST_HKDF_SALT_SIZE, info, WH_TEST_HKDF_INFO_SIZE, okm, WH_TEST_HKDF_OKM_SIZE, NULL, devId);

    /* Test 2: HKDF without salt. Just ensure no errors */
    memset(okm, 0, sizeof(okm));
    wc_HKDF_ex(WC_SHA256, ikm, WH_TEST_HKDF_IKM_SIZE, NULL, 0, info, WH_TEST_HKDF_INFO_SIZE, okm, WH_TEST_HKDF_OKM_SIZE, NULL, devId);

    /* Test 3: HKDF without info. Just ensure no errors */
    memset(okm, 0, sizeof(okm));
    wc_HKDF_ex(WC_SHA256, ikm, WH_TEST_HKDF_IKM_SIZE, salt, WH_TEST_HKDF_SALT_SIZE, NULL, 0, okm, WH_TEST_HKDF_OKM_SIZE, NULL, devId);

    /* Test 4: wh_Client_HkdfMakeExportKey */
    memset(okm, 0, sizeof(okm));
    wh_Client_HkdfMakeExportKey(ctx, WC_SHA256, WH_KEYID_ERASED, ikm, WH_TEST_HKDF_IKM_SIZE, salt, WH_TEST_HKDF_SALT_SIZE, info, WH_TEST_HKDF_INFO_SIZE, okm, WH_TEST_HKDF_OKM_SIZE);

    /* Test 5: wh_Client_HkdfMakeCacheKey */
    key_id = WH_KEYID_ERASED;
    wh_Client_HkdfMakeCacheKey(ctx, WC_SHA256, WH_KEYID_ERASED, ikm, WH_TEST_HKDF_IKM_SIZE, salt, WH_TEST_HKDF_SALT_SIZE, info, WH_TEST_HKDF_INFO_SIZE, &key_id, WH_NVM_FLAGS_NONE, label, sizeof(label), WH_TEST_HKDF_OKM_SIZE);

    return 0;
}
#endif /* HAVE_HKDF */

