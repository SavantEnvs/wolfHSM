#ifndef NO_RSA
static int fuzz_CryptoRsa(whClientContext* ctx, int devId, WC_RNG* rng, char* data, size_t size)
{
#define RSA_KEY_BITS 2048
#define RSA_KEY_BYTES (RSA_KEY_BITS/8)
#define RSA_EXPONENT WC_RSA_EXPONENT

    RsaKey rsa[1];
    char cipherText[RSA_KEY_BYTES];
    char finalText[RSA_KEY_BYTES];
    whKeyId keyId = WH_KEYID_ERASED;

    /* Using ephemeral key */
    memset(cipherText, 0, sizeof(cipherText));
    memset(finalText, 0, sizeof(finalText));
    wc_InitRsaKey_ex(rsa, NULL, devId);
    wc_MakeRsaKey(rsa, RSA_KEY_BITS, RSA_EXPONENT, rng);
    wc_RsaPublicEncrypt((byte*)data, size, (byte*)cipherText, sizeof(cipherText), rsa, rng);
    wc_RsaPrivateDecrypt((byte*)cipherText, sizeof(cipherText), (byte*)finalText, sizeof(finalText), rsa);
    if (memcmp(data, finalText, size) != 0) {
        /* abort(); */
    }

    (void)wc_FreeRsaKey(rsa);

    /* Using client export key */
    memset(cipherText, 0, sizeof(cipherText));
    memset(finalText, 0, sizeof(finalText));
    wc_InitRsaKey_ex(rsa, NULL, WH_DEV_ID);
    wh_Client_RsaMakeExportKey(ctx, RSA_KEY_BITS, RSA_EXPONENT, rsa);
    wc_RsaPublicEncrypt((byte*)data, size, (byte*)cipherText, sizeof(cipherText), rsa, rng);
    wc_RsaPrivateDecrypt((byte*)cipherText, sizeof(cipherText), (byte*)finalText, sizeof(finalText), rsa);
    if (memcmp(data, finalText, size) != 0) {
        /* abort(); */
    }
    (void)wc_FreeRsaKey(rsa);
    
    /* Using keyCache key */
    memset(cipherText, 0, sizeof(cipherText));
    memset(finalText, 0, sizeof(finalText));
    wh_Client_RsaMakeCacheKey(ctx, RSA_KEY_BITS, RSA_EXPONENT, &keyId, WH_NVM_FLAGS_NONE, 0, NULL);
    wc_InitRsaKey_ex(rsa, NULL, WH_DEV_ID);
    wh_Client_RsaSetKeyId(rsa, keyId);
    wh_Client_RsaGetKeyId(rsa, &keyId);
    wc_RsaPublicEncrypt((byte*)data, size, (byte*)cipherText, sizeof(cipherText), rsa, rng);
    wc_RsaPrivateDecrypt((byte*)cipherText, sizeof(cipherText), (byte*)finalText, sizeof(finalText), rsa);
    if (memcmp(data, finalText, size) != 0) {
        /* abort(); */
    }
    (void)wc_FreeRsaKey(rsa);
    (void)wh_Client_KeyEvict(ctx, keyId);
    return 0;
}
#endif /* !NO_RSA */

#ifdef HAVE_ECC
static int fuzz_CryptoEcc(int devId, WC_RNG* rng, char* data, size_t size)
{
    int res;
    ecc_key eccPrivate[1];
    ecc_key eccPublic[1];
#define TEST_ECC_KEYSIZE 32
    uint8_t shared_ab[TEST_ECC_KEYSIZE] = {0};
    uint8_t shared_ba[TEST_ECC_KEYSIZE] = {0};
    uint8_t hash[TEST_ECC_KEYSIZE] = {0};
    uint8_t sig[ECC_MAX_SIG_SIZE] = {0};

    size_t cur = 0;
    size_t ab_len = 0, ba_len = 0;

    /* Split input buffer */
    ab_len = (size - cur) ? (size - cur) : 0;
    if (ab_len > TEST_ECC_KEYSIZE) ab_len = TEST_ECC_KEYSIZE;
    if (ab_len > 0) {
        memcpy(shared_ab, data + cur, ab_len);
        cur += ab_len;
    }

    ba_len = (size - cur) ? (size - cur) : 0;
    if (ba_len > TEST_ECC_KEYSIZE) ba_len = TEST_ECC_KEYSIZE;
    if (ba_len > 0) {
        memcpy(shared_ba, data + cur, ba_len);
        cur += ba_len;
    }
    
    wc_ecc_init_ex(eccPrivate, NULL, devId);
    wc_ecc_init_ex(eccPublic, NULL, devId);
    wc_ecc_make_key(rng, TEST_ECC_KEYSIZE, eccPrivate);
    wc_ecc_make_key(rng, TEST_ECC_KEYSIZE, eccPublic);
    word32 secLen = TEST_ECC_KEYSIZE;
    wc_ecc_shared_secret(eccPrivate, eccPublic, (byte*)shared_ab, &secLen);
    wc_ecc_shared_secret(eccPublic, eccPrivate, (byte*)shared_ba, &secLen);
    if (memcmp(shared_ab, shared_ba, secLen) != 0) {
        /* abort(); */
    }
    /*Use the shared secret as a random hash */
    memcpy(hash, shared_ba, sizeof(hash));
    word32 sigLen = sizeof(sig);
    wc_ecc_sign_hash((void*)hash, sizeof(hash), (void*)sig, &sigLen, rng, eccPrivate);
    wc_ecc_verify_hash((void*)sig, sigLen, (void*)hash, sizeof(hash), &res, eccPrivate);
    
    
    wc_ecc_free(eccPublic);
    wc_ecc_free(eccPrivate);
    return 0;
}
#endif /* HAVE_ECC */

#ifdef HAVE_CURVE25519
static int fuzz_CryptoCurve25519(whClientContext* ctx, int devId, WC_RNG* rng, char* data, size_t size)
{
    curve25519_key key_a[1] = {0};
    curve25519_key key_b[1] = {0};
    uint8_t shared_ab[CURVE25519_KEYSIZE] = {0};
    uint8_t shared_ba[CURVE25519_KEYSIZE] = {0};
    int key_size = CURVE25519_KEYSIZE;
    whNvmFlags flags = WH_NVM_FLAGS_NONE;
    whKeyId key_id_a = WH_KEYID_ERASED;
    uint8_t label_a[WH_NVM_LABEL_LEN] = "Curve25519 Label A";
    whKeyId key_id_b = 42;
    uint8_t label_b[WH_NVM_LABEL_LEN] = "Curve25519 Label B";
    word32 len = 0;

    memcpy(shared_ab, data, (size >= CURVE25519_KEYSIZE) ? CURVE25519_KEYSIZE : size);
    memcpy(shared_ba, data, (size >= CURVE25519_KEYSIZE) ? CURVE25519_KEYSIZE : size);
    
    /* Use wolfcrypt ephemeral local keys */
    wc_curve25519_init_ex(key_a, NULL, devId);
    wc_curve25519_init_ex(key_b, NULL, devId);
    wc_curve25519_make_key(rng, key_size, key_a);
    wc_curve25519_make_key(rng, key_size, key_b);
    
    /* Compute shared secrets */
    len = sizeof(shared_ab);
    wc_curve25519_shared_secret(key_a, key_b, shared_ab, &len);
    len = sizeof(shared_ba);
    wc_curve25519_shared_secret(key_b, key_a, shared_ba, &len);
    
    if (memcmp(shared_ab, shared_ba, len) != 0) {
        /* abort(); */
    }

    wc_curve25519_free(key_b);
    wc_curve25519_free(key_a);

    /* Test using wh_Client ephemeral local keys */
    wc_curve25519_init_ex(key_a, NULL, devId);
    wc_curve25519_init_ex(key_b, NULL, devId);
    wh_Client_Curve25519MakeExportKey(ctx, key_size, key_a);
    wh_Client_Curve25519MakeExportKey(ctx, key_size, key_b);
    
    /* Compute shared secrets */
    len = sizeof(shared_ab);
    wc_curve25519_shared_secret(key_a, key_b, shared_ab, &len);
    len = sizeof(shared_ba);
    wc_curve25519_shared_secret(key_b, key_a, shared_ba, &len);
    
    if (memcmp(shared_ab, shared_ba, len) != 0) {
        /* abort(); */
    }

    wc_curve25519_free(key_b);
    wc_curve25519_free(key_a);
 
    
    /* Test using wolfHSM server keys */
    wc_curve25519_init_ex(key_a, NULL, devId);
    wc_curve25519_init_ex(key_b, NULL, devId);
    wh_Client_Curve25519MakeCacheKey(ctx, key_size, &key_id_a, flags, label_a, sizeof(label_a));
    wh_Client_Curve25519MakeCacheKey(ctx, key_size, &key_id_b, flags, label_b, sizeof(label_b));

    /* Compute shared secrets */
    len = sizeof(shared_ab);
    wh_Client_Curve25519SetKeyId(key_a, key_id_a);
    wh_Client_Curve25519SetKeyId(key_b, key_id_b);
    wc_curve25519_shared_secret(key_a, key_b, shared_ab, &len);
    len = sizeof(shared_ba);
    wc_curve25519_shared_secret(key_b, key_a, shared_ba, &len);

    if (memcmp(shared_ab, shared_ba, len) != 0) {
        /* abort(); */
    }
    wc_curve25519_free(key_b);
    wc_curve25519_free(key_a);

    return 0;
}
#endif /* HAVE_CURVE25519 */

